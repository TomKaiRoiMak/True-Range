-- luajit tools/thing_sources.lua <out .lua> <data .lua>[,<data .lua>...] <scripts root> [<scripts root>...]
-- For each thing the data has as struck with in its own boss's move (in_move) - its blows the boss's,
-- seen where it stands - which prefabs set it off through a component of theirs: the component's code
-- names it ("groundpoundring_fx" in components/groundpounder.lua), and those prefabs add that
-- component (AddComponent("groundpounder") in their prefab's file, or a mod's post-init of it). A
-- pound's ring is the Minotaur's leap's - and the Great Depths Worm's dirt's, a groundpounder too:
-- struck with there as well. Not a thing a prefab's own code sets off for show (Uncompromising Mode's
-- Bearger's rock: its ring only a picture). true_range/predict: such a thing drawn alone only with its
-- own boss near, or one of these right where it is.
local out_path = arg[1]
local names = {}
for f in arg[2]:gmatch("[^,]+") do
    DEGREES, FRAMES = math.pi / 180, 1 / 30
    local ok, d = pcall(dofile, f)
    if ok and type(d) == "table" then
        for k, h in pairs(d._hazards or {}) do if h.in_move then names[k] = true end end
    end
end
local function Read(p)
    local fh = io.open(p, "rb")
    if fh == nil then return nil end
    local t = fh:read("*a")
    fh:close()
    return t
end
local function Files(dir)
    local l = {}
    local p = io.popen('dir /b /s "' .. dir:gsub("/", "\\") .. '\\*.lua" 2>nul')
    if p == nil then return l end
    for line in p:lines() do l[#l + 1] = line end
    p:close()
    return l
end
local sources = {}
for i = 3, #arg do
    local root = arg[i]
    local comps = {}   -- component name -> things it names
    for _, f in ipairs(Files(root .. "\\components")) do
        local text = Read(f)
        local cname = f:match("([%w_]+)%.lua$")
        if text ~= nil and cname ~= nil then
            for n in pairs(names) do
                if text:find('"' .. n .. '"', 1, true) then
                    comps[cname] = comps[cname] or {}
                    comps[cname][#comps[cname] + 1] = n
                end
            end
        end
    end
    -- (prefab files - and a mod's post-inits - adding one of those components)
    for _, f in ipairs(Files(root)) do
        if not f:find("\\components\\", 1, true) then
            local text = Read(f)
            if text ~= nil then
                for cname, things in pairs(comps) do
                    if text:find('AddComponent("' .. cname .. '")', 1, true) then
                        local owners = {}
                        for p in text:gmatch('Prefab%(%s*"([%w_]+)"') do owners[#owners + 1] = p end
                        for p in text:gmatch('AddPrefabPostInit%(%s*"([%w_]+)"') do owners[#owners + 1] = p end
                        for _, n in ipairs(things) do
                            sources[n] = sources[n] or {}
                            for _, p in ipairs(owners) do sources[n][p] = true end
                        end
                    end
                end
            end
        end
    end
end
local keys = {}
for n in pairs(sources) do keys[#keys + 1] = n end
table.sort(keys)
local lines = { "-- generated by tools/thing_sources.lua: things struck with in their boss's move (in_move), and the",
    "-- prefabs that set each off through a component of theirs - true_range/predict draws one alone only",
    "-- with its own boss near, or one of these where it is", "return {" }
for _, n in ipairs(keys) do
    local l = {}
    for p in pairs(sources[n]) do l[#l + 1] = string.format("%q", p) end
    table.sort(l)
    lines[#lines + 1] = string.format("    %s = { %s },", n, table.concat(l, ", "))
end
lines[#lines + 1] = "}"
local fh = assert(io.open(out_path, "wb"))
fh:write(table.concat(lines, "\n") .. "\n")
fh:close()
for _, n in ipairs(keys) do
    local c = 0
    for _ in pairs(sources[n]) do c = c + 1 end
    print(string.format("%s: %d prefabs", n, c))
end
